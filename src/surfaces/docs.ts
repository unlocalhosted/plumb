import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import type { PlumbConfig } from '../config.js';
import type { Report } from '../report.js';
import { renderLoop } from './agent.js';

/** Optional future ownership/habit records stay data; absent layers are explicit. */
export function agentDocs(report: Report, config: PlumbConfig): string {
  const sections = ['# Plumb\n\nGenerated by `plumb agent-docs`. Read decisions here; regenerate when their sources change.'];
  const families = [...new Set(report.decisions.map(d => d.family))].sort();
  for (const family of families) {
    const policy = config.decisions?.[family];
    const decisions = report.decisions.filter(d => d.family === family && (policy?.origins ?? ['project', 'inferred']).includes(d.origin));
    if (!decisions.length) continue;
    const identity = policy?.identity ?? (['color', 'motion'].includes(family) ? 'reference' : 'value');
    const callers = policy?.callers ?? (decisions.some(d => d.tier === 'semantic') ? ['semantic'] : ['primitive', 'semantic']);
    sections.push(`## ${family}\n\nIdentity: ${identity}. Caller tiers: ${callers.join(', ')}.\n\n` +
      decisions.map(d => `- ${d.name}: ${d.value}${d.resolved && d.resolved !== d.value ? ` (${d.resolved})` : ''}; ${d.origin}, ${d.tier}.\n  References: ${d.refs.join(', ')}.\n  Why: ${d.why || '(no reason recorded)'}`).join('\n'));
  }
  // Ownership's report schema is supplied by Layer 7; do not substitute guessed contracts.
  const ownership = (report as Report & { components?: unknown; ownership?: unknown }).components ?? (report as Report & { ownership?: unknown }).ownership;
  sections.push(`## Components\n\n${ownership === undefined ? 'No component ownership data in this report.' : 'Recorded ownership and caller permissions:\n\n```json\n' + JSON.stringify(ownership, null, 2) + '\n```'}`);
  const recorded = report.habits ?? [];
  sections.push(`## Habits\n\n${config.habits?.length ? config.habits.map(habit => {
    const id = typeof habit === 'string' ? habit : habit.id;
    const record = recorded.find(h => h.id === id);
    const why = typeof habit === 'string' ? record?.reason : habit.message;
    return `- ${id}. Why: ${why || '(no reason supplied by the habit record)'}`;
  }).join('\n') : 'None enabled.'}`);
  sections.push(renderLoop().trimEnd());
  return sections.join('\n\n') + '\n';
}
export async function writeAgentDocs(report: Report, config: PlumbConfig): Promise<string> {
  await writeFile(resolve(report.root, 'PLUMB.md'), agentDocs(report, config), 'utf8');
  return 'Wrote PLUMB.md. Add this block to AGENTS.md or CLAUDE.md:\n\n' +
    'Read PLUMB.md for design decisions and reasons.\nRun `plumb check --changed --agent` after edits; stop on "0 new".\n' +
    'Never edit config, ledger, or theme to pass. If no decision fits, report NEEDS-DECISION.\n';
}
