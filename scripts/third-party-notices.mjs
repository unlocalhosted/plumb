import { access, readFile, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, posix } from 'node:path';
import { parseSync } from 'oxc-parser';
import { overlayClient, overlayModules } from '../dist/hosts/client.js';

// tsc preserves external Node imports; it does not bundle those dependencies.
// Browser vendor module bodies are copied at the serving boundary. Derive
// their package inventory from that boundary and verify its whole import graph.
const require = createRequire(import.meta.url);
const packages = new Set();
const shipped = new Set();
const imports = (file, code) => {
  const parsed = parseSync(file, code);
  if (parsed.errors.length) throw new Error(`Cannot audit ${file}: ${parsed.errors[0].message}`);
  return parsed.program.body.filter(statement => statement.source && statement.importKind !== 'type' && statement.exportKind !== 'type'
    && (!statement.specifiers?.length || statement.specifiers.some(specifier => specifier.importKind !== 'type' && specifier.exportKind !== 'type')))
    .map(statement => statement.source.value);
};
for (const module of overlayModules.filter(path => path.endsWith('.js'))) {
  const vendor = /^vendor\/((?:@[^/]+\/)?[^/]+)\//.exec(module);
  if (vendor) { packages.add(vendor[1]); shipped.add(vendor[1]); }
  // Read upstream vendor bytes directly: serving adds the generated license
  // banner, which must not become an input to its own regeneration.
  const code = vendor ? await readFile(join(dirname(require.resolve(`${vendor[1]}/source`)), posix.basename(module)), 'utf8') : await overlayClient(module);
  for (const specifier of imports(module, code)) {
    const target = posix.normalize(posix.join(posix.dirname(module), specifier));
    if (!specifier.startsWith('.') || !overlayModules.includes(target)) {
      throw new Error(`Unaudited overlay dependency ${specifier} in ${module}; add its served module and license.`);
    }
  }
}
// Flat vendor output hides embedded imports. Audit the vendor's published
// source graph too, skipping type-only dependencies. Missing source metadata
// is a release error, never permission to omit a license.
const sourceEntries = { bippy: ['src/source/index.ts', 'src/core.ts', 'src/rdt-hook.ts'] };
const visited = new Set();
async function auditSource(file) {
  if (visited.has(file)) return;
  visited.add(file);
  for (const specifier of imports(file, await readFile(file, 'utf8'))) {
    if (specifier.startsWith('.')) {
      const target = join(dirname(file), specifier);
      const candidates = [target.replace(/\.js$/, '.ts'), target, join(target, 'index.ts')];
      let resolved;
      for (const candidate of candidates) { try { await access(candidate); resolved = candidate; break; } catch {} }
      if (!resolved) throw new Error(`Missing vendor source ${specifier} in ${file}`);
      await auditSource(resolved);
    } else if (!specifier.startsWith('node:')) {
      const name = specifier.split('/').slice(0, specifier.startsWith('@') ? 2 : 1).join('/');
      packages.add(name);
      await auditSource(createRequire(file).resolve(specifier));
    }
  }
}
for (const name of shipped) {
  if (!sourceEntries[name]) throw new Error(`Add published source entrypoints for bundled dependency ${name}`);
  const root = dirname(require.resolve(`${name}/package.json`));
  for (const source of sourceEntries[name]) await auditSource(join(root, source));
}
// bippy's owner-stack/rdt-hook implementation adapts React/React DevTools code.
// Preserve the upstream MIT attribution as well as bippy's own MIT license.
if (shipped.has('bippy')) packages.add('react');
let notices = 'THIRD-PARTY NOTICES\n\nGenerated by npm run notices.\n'
  + 'Covers the served overlay vendor modules and their upstream attributions.\n'
  + 'Node dependencies remain external npm packages with their own licenses.\n\n';
for (const name of [...packages].sort()) {
  const root = dirname(require.resolve(`${name}/package.json`));
  const metadata = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
  const licenses = (await readdir(root)).filter(file => /^(?:licen[cs]e|copying|notice)(?:[.-]|$)/i.test(file)).sort();
  if (!licenses.length) throw new Error(`No license text found for ${name}`);
  const label = shipped.has(name) ? `${name}@${metadata.version}` : name === 'react' ? 'react (upstream code adapted by bippy)' : `${name} (embedded in vendor output; license from installed ${metadata.version})`;
  notices += `===== ${label} — ${metadata.license} =====\n\n`;
  for (const file of licenses) notices += `${file}\n\n${(await readFile(join(root, file), 'utf8')).trim()}\n\n`;
}
const destination = new URL('../THIRD_PARTY_NOTICES', import.meta.url);
notices = notices.trimEnd() + '\n';
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== notices) throw new Error('THIRD_PARTY_NOTICES is stale. Run npm run notices.');
} else await writeFile(destination, notices);
