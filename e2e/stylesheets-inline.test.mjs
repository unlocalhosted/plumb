import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cp, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';

const root = fileURLToPath(new URL('../', import.meta.url));
const cli = join(root, 'dist/cli.js');
function run(directory, args = []) {
  const result = spawnSync(process.execPath, [cli, '--root', directory, ...args, '--json'], { encoding: 'utf8', timeout: 10_000 });
  assert.ifError(result.error);
  assert.equal(result.stderr, '');
  assert.ok(result.status === 0 || result.status === 1, result.stdout);
  return { status: result.status, report: JSON.parse(result.stdout) };
}

test('component modules provide CSS existence proof across workspace and package boundaries', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'plumb-module-css-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await cp(join(root, 'fixtures/module-css'), directory, { recursive: true });
  const cold = run(directory).report;
  assert.deepEqual(cold.findings.map(finding => finding.declaration.value), ['kit-unused']);
  assert.match(cold.findings[0].fix, /unreachable.css, which nothing imports/);
  assert.equal(cold.moduleGraph.followed, 4);
  assert.equal(cold.moduleGraph.cssFiles, 3);
  const kit = cold.stylesheets.find(sheet => sheet.file.endsWith('/kit.css'));
  assert.equal(kit.sourceOrigin, 'framework');
  assert.equal(kit.package, 'ui-kit');
  assert.equal(kit.reached[0].kind, 'module');
  assert.ok(!cold.declarations.some(d => d.site.file.includes('/packages/ui-kit/')), 'module CSS outside source globs is existence proof only');
  const warm = run(directory).report;
  assert.deepEqual(warm.findings, cold.findings);
  assert.deepEqual(warm.declarations, cold.declarations);
  assert.equal(warm.moduleGraph.cacheMisses, 0);
  await writeFile(join(directory, 'packages/ui-kit/dynamic.js'), "import './unreachable.css';");
  const changed = run(directory).report;
  assert.deepEqual(changed.findings.map(f => f.declaration.value), ['kit-lazy']);
  await mkdir(join(directory, 'node_modules/ui-kit'), { recursive: true });
  await cp(join(directory, 'packages/ui-kit'), join(directory, 'node_modules/ui-kit'), { recursive: true });
  await writeFile(join(directory, 'node_modules/ui-kit/package.json'), JSON.stringify({ name: 'ui-kit', exports: { browser: './index.js', import: './wrong.js', default: './wrong.js' } }));
  await rm(join(directory, 'tsconfig.json'));
  const packageReport = run(directory).report;
  assert.deepEqual(packageReport.findings.map(f => f.declaration.value), ['kit-lazy']);
  assert.ok(packageReport.stylesheets.some(sheet => sheet.file.includes('/node_modules/ui-kit/kit.css')));
  await writeFile(join(directory, 'node_modules/ui-kit/empty.js'), 'export const Button = "button";');
  await writeFile(join(directory, 'node_modules/ui-kit/package.json'), JSON.stringify({ name: 'ui-kit', exports: { default: './empty.js' } }));
  const defaultExport = run(directory).report;
  assert.equal(defaultExport.moduleGraph.cssFiles, 0, 'independent package-export edit invalidates cached graph reachability');
  assert.ok(defaultExport.findings.some(f => f.declaration.value === 'kit-button'));
  await writeFile(join(directory, 'node_modules/ui-kit/package.json'), JSON.stringify({ name: 'ui-kit', exports: { import: './button.js', default: './wrong.js' } }));
  const exported = run(directory).report;
  assert.ok(exported.stylesheets.some(sheet => sheet.file.endsWith('/button.css')));
  await writeFile(join(directory, 'node_modules/ui-kit/kit.css'), '.kit-renamed { padding: 5px; }');
  assert.ok(run(directory).report.findings.some(f => f.declaration.value === 'kit-btn'), 'CSS edits invalidate selector proof');
  await writeFile(join(directory, 'node_modules/ui-kit/kit.css'), ".kit-btn { padding: 4px; } @import './button.css';");
  await writeFile(join(directory, 'node_modules/ui-kit/button.js'), "import './kit.css';\nexport const Button = 'button';");
  await writeFile(join(directory, 'node_modules/ui-kit/index.d.ts'), "import './unreachable.css'; export type Never = string;");
  await writeFile(join(directory, 'src/App.tsx'), "import { Button } from 'ui-kit'; import type { Never } from '../node_modules/ui-kit/index.d.ts'; export type { Never as Other } from '../node_modules/ui-kit/index.d.ts'; const text = '😀'; const lazy = () => import('../node_modules/ui-kit/\\u0064ynamic.js'); import('./' + variable); <Button className='kit-btn kit-button kit-unused' />;");
  await writeFile(join(directory, 'node_modules/ui-kit/dynamic.js'), "import './unreachable.css';");
  const dynamic = run(directory).report;
  assert.deepEqual(dynamic.findings, [], 'escaped literal dynamic import is followed after Unicode text');
  assert.equal(dynamic.moduleGraph.followed, 2, 'type-only declaration imports and nonliteral dynamic imports are skipped');
  assert.equal(dynamic.moduleGraph.cssFiles, 3, 'CSS descendants count as module-reached files');
  await writeFile(join(directory, 'node_modules/ui-kit/dynamic.js'), 'export const value = 1;');
  assert.deepEqual(run(directory).report.findings.map(f => f.declaration.value), ['kit-unused'], 'type-only imports never supply CSS proof');
  await writeFile(join(directory, 'tsconfig.json'), JSON.stringify({ compilerOptions: { paths: { 'ui-kit': ['./packages/ui-kit/index.js'] } } }));
  await writeFile(join(directory, 'plumb.config.ts'), "export default { source: ['src/**/*.tsx', 'packages/ui-kit/kit.css'] };");
  const explicit = run(directory).report;
  const sheet = explicit.stylesheets.find(s => s.file.endsWith('/packages/ui-kit/kit.css'));
  assert.equal(sheet.sourceOrigin, 'project', 'explicit source CSS remains a project site');
  assert.ok(explicit.declarations.some(d => d.site.file === sheet.file && d.sourceOrigin === 'project'));
});

test('stylesheet and inline feature slice through real CLI and explain', async t => {
  const directory = await mkdtemp(join(root, 'fixtures/.layer2-e2e-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await cp(join(root, 'fixtures/stylesheets-inline'), directory, { recursive: true });
  await writeFile(join(directory, 'plumb.config.ts'), "export default { css: 'styles/entry.css', source: ['src/**/*.{tsx,js,css}', 'styles/{entry,source,imported}.css'] };");
  const first = run(directory);
  assert.equal(first.status, 1);
  assert.deepEqual(first.report.findings.filter(finding => finding.rule.startsWith('existence/')).map(finding => finding.declaration.value), ['forgotten']);
  assert.match(first.report.findings[0].fix, /declared in styles\/unreachable.css, which nothing imports/);
  const page = first.report.stylesheets.find(sheet => sheet.file.endsWith('/src/page.css'));
  assert.deepEqual(page.reached, [{ kind: 'side-effect', from: join(directory, 'src/App.tsx'), specifier: './page.css' }, { kind: 'source' }]);
  assert.ok(first.report.stylesheets.some(sheet => sheet.sourceOrigin === 'framework' && sheet.reached.some(reach => reach.kind === 'import')));
  assert.ok(first.report.stylesheets.some(sheet => sheet.sourceOrigin === 'framework' && sheet.package === 'tailwindcss'));
  assert.ok(!first.report.declarations.some(declaration => declaration.package === 'tailwindcss'));
  const entry = run(directory, ['explain', 'styles/entry.css']).report.declarations;
  assert.ok(entry.some(declaration => declaration.origin === 'apply' && declaration.prop === 'gap' && declaration.value === 'calc(var(--spacing) * 4)' && declaration.site.line === 6 && declaration.site.column === 3));
  assert.ok(entry.some(declaration => declaration.origin === 'apply' && declaration.prop === 'gap' && declaration.value === '13px' && declaration.site.line === 6));
  assert.ok(entry.some(declaration => declaration.prop === 'color' && declaration.value === '#123456'));
  assert.ok(entry.some(declaration => declaration.prop === 'padding' && declaration.value === 'var(--spacing)'));
  assert.ok(entry.some(declaration => declaration.when.some(condition => condition.kind === 'pseudo' && condition.text === ':hover')));
  const css = run(directory, ['explain', 'src/page.css']).report.declarations;
  const hovered = css.find(declaration => declaration.prop === 'gap' && declaration.value === '3px');
  assert.equal(hovered.site.line, 6);
  assert.equal(hovered.site.column, 29);
  assert.ok(hovered.when.some(condition => condition.kind === 'selector' && condition.text === '.outer:hover'));
  assert.ok(hovered.when.some(condition => condition.kind === 'pseudo' && condition.text === ':hover'));
  assert.ok(hovered.when.some(condition => condition.kind === 'media' && condition.text === '(hover: hover)'));
  assert.ok(hovered.when.some(condition => condition.kind === 'layer' && condition.text === 'components'));
  assert.ok(css.find(declaration => declaration.prop === 'display').when.some(condition => condition.kind === 'container'));
  assert.ok(css.find(declaration => declaration.prop === 'display').when.some(condition => condition.kind === 'supports'));
  assert.equal(css.find(declaration => declaration.when.some(condition => condition.text === '.plain')).when.some(condition => condition.kind === 'pseudo'), false, 'sibling selector cannot inherit hover');
  assert.equal(css.filter(declaration => declaration.origin === 'keyframes').length, 3);
  assert.ok(css.some(declaration => declaration.prop === '--literal' && declaration.origin === 'custom-property' && declaration.site.line === 15));
  assert.ok(css.some(declaration => declaration.prop === 'color' && declaration.site.line === 16), 'final semicolon optional');
  const imported = run(directory, ['explain', 'styles/imported.css']).report.declarations;
  assert.deepEqual(imported[0].when.filter(condition => condition.kind !== 'selector'), [
    { kind: 'layer', text: 'components' }, { kind: 'supports', text: 'display: grid' }, { kind: 'media', text: '(width > 600px)' },
  ]);
  const reference = run(directory, ['explain', 'src/reference.css']).report.declarations;
  assert.equal(reference.find(declaration => declaration.prop === 'gap').origin, 'apply');
  assert.equal(reference.find(declaration => declaration.prop === 'gap').site.line, 3);
  const jsx = run(directory, ['explain', 'src/App.tsx']).report;
  assert.ok(jsx.sites.find(site => site.token === 'room-gap').declarations.some(declaration => declaration.prop === 'gap' && declaration.value === '13px'));
  const inline = jsx.declarations.filter(declaration => declaration.origin === 'inline' || (declaration.origin === 'custom-property' && declaration.owner.name === 'div'));
  const at = (prop, line) => inline.find(declaration => declaration.prop === prop && declaration.site.line === line);
  assert.equal(at('gap', 7).value, '10px');
  assert.equal(at('line-height', 7).value, '1.5');
  assert.equal(at('--x', 7).origin, 'custom-property');
  assert.equal(at('--x', 7).value, '13px');
  assert.equal(at('color', 7).value, 'dynamic-value');
  assert.equal(at('color', 7).opaque, 'dynamic-value');
  assert.equal(at('*', 8).opaque, 'spread');
  assert.equal(at('*', 8).owner.name, 'Button');
  assert.equal(at('margin-top', 9).value, '-2px');
  assert.equal(at('-ms-flex', 9).value, '2');
  assert.equal(at('padding-top', 10).value, '0');
  assert.equal(at('-webkit-line-clamp', 10).value, '2');
  assert.equal(at('stroke-width', 10).value, '3');
  assert.ok(jsx.declarations.some(declaration => declaration.origin === 'stylesheet' && declaration.site.line === 12 && declaration.prop === 'gap'));
  assert.ok(jsx.declarations.some(declaration => declaration.origin === 'stylesheet' && declaration.site.line === 15 && declaration.prop === 'gap'), 'escaped string maps to JSX source');
  assert.deepEqual(first.report.coverage.inline, { sites: 4, literalSites: 3, opaque: 2, fullyOpaque: 1, spreads: 1 });
  assert.equal(first.report.coverage.stylesheets['jsx-style'], 2);
  assert.ok(first.report.coverage.declarations.apply >= 3);
  const warm = run(directory).report;
  assert.deepEqual(warm.declarations, first.report.declarations);
  assert.equal(warm.timing.cacheMisses, 0);
  await writeFile(join(directory, 'src/page.css'), (await readFile(join(directory, 'src/page.css'), 'utf8')) + '\n.changed { gap: 22px; }');
  assert.ok(run(directory).report.declarations.some(declaration => declaration.value === '22px'), 'plain CSS edit invalidates lowering cache');
  await writeFile(join(directory, 'src/App.tsx'), (await readFile(join(directory, 'src/App.tsx'), 'utf8')) + "\nimport '../styles/imported.css';");
  const contexts = run(directory, ['explain', 'styles/imported.css']).report.declarations;
  assert.equal(contexts.length, 2, 'scoped CSS import and independent JS import retain both contexts');
  assert.ok(contexts.some(declaration => !declaration.when.some(condition => condition.kind === 'media')));
  await writeFile(join(directory, 'src/imported-style.ts'), 'export const BOX = { gap: 11, lineHeight: 2 } as const;');
  await writeFile(join(directory, 'src/App.tsx'), (await readFile(join(directory, 'src/App.tsx'), 'utf8')) + "\nimport { BOX as IMPORTED } from './imported-style';\n<div style={IMPORTED}/>;\nconst ALIAS = IMPORTED; <div style={ALIAS}/>;\nfunction Shadow(IMPORTED) { return <div style={IMPORTED}/>; }\n<Host play={{ node: <button style={{ gap: 17 }}/> }} solid={<span style={{ lineHeight: 3 }}/>}/>;");
  const constants = run(directory, ['explain', 'src/App.tsx']).report.declarations;
  assert.ok(constants.some(declaration => declaration.origin === 'inline' && declaration.prop === 'gap' && declaration.value === '11px'));
  assert.ok(constants.some(declaration => declaration.origin === 'inline' && declaration.prop === 'line-height' && declaration.value === '2'));
  assert.ok(constants.some(declaration => declaration.opaque === 'spread' && declaration.site.line === 22), 'second-hop alias remains opaque');
  assert.ok(constants.some(declaration => declaration.opaque === 'spread' && declaration.site.line === 23), 'parameter shadows imported const');
  assert.ok(constants.some(declaration => declaration.prop === 'gap' && declaration.value === '17px' && declaration.owner.name === 'button'), 'JSX inside object-valued props is scanned');
  assert.ok(constants.some(declaration => declaration.prop === 'line-height' && declaration.value === '3' && declaration.owner.name === 'span'), 'direct JSX-valued prop is scanned');
});

test('package side-effect CSS uses style exports and retains framework provenance', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'plumb-package-css-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await mkdir(join(directory, 'src'), { recursive: true });
  await mkdir(join(directory, 'node_modules/css-pkg'), { recursive: true });
  await writeFile(join(directory, 'src/App.tsx'), "import 'css-pkg/x.css'; import 'css-pkg'; <div className='package-class'/>");
  await writeFile(join(directory, 'node_modules/css-pkg/package.json'), JSON.stringify({ name: 'css-pkg', exports: { '.': { style: './actual.css', default: './bad.js' }, './x.css': { style: './actual.css', default: './bad.js' } } }));
  await writeFile(join(directory, 'node_modules/css-pkg/actual.css'), '.package-class { gap: 6px; }');
  const { report, status } = run(directory);
  assert.equal(status, 0);
  assert.deepEqual(report.declarations, [], 'package CSS outside source globs is existence proof only');
  assert.equal(report.stylesheets[0].sourceOrigin, 'framework');
  assert.equal(report.stylesheets[0].package, 'css-pkg');
  assert.equal(report.stylesheets[0].reached[0].kind, 'side-effect');
  assert.equal(report.stylesheets[0].reached.length, 2, 'package root resolves CSS through style export');
});

test('plain-css fixture lowers outside repository with no Tailwind resolvable', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'plumb-no-tailwind-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await cp(join(root, 'fixtures/plain-css'), directory, { recursive: true });
  await writeFile(join(directory, 'src/quoted.css'), '/* @apply should not load Tailwind */\n.quoted[data-x="{"] { content: "@import \'missing.css\'; @apply gap-4; var(--not-a-ref)"; --payload: { x: y; }; }\n@keyframes quoted { from { content: "}"; opacity: 0; } to { opacity: 1; } }');
  assert.throws(() => createRequire(join(directory, 'package.json')).resolve('tailwindcss'), { code: 'MODULE_NOT_FOUND' });
  const { report, status } = run(directory);
  assert.equal(status, 0);
  assert.deepEqual(report.tailwind, { entry: null, version: null });
  assert.ok(report.declarations.some(declaration => declaration.prop === '--space-small' && declaration.value === '4px'));
  assert.ok(report.declarations.some(declaration => declaration.prop === 'padding' && declaration.value === 'var(--space-medium)'));
  assert.equal(report.timing.phases.load, 0);
  assert.equal(report.timing.phases.compile, 0);
  assert.ok(report.declarations.some(declaration => declaration.prop === '--payload' && declaration.value === '{ x: y; }'));
  assert.ok(report.declarations.some(declaration => declaration.prop === 'content' && declaration.refs.length === 0));
  assert.equal(report.declarations.filter(declaration => declaration.origin === 'keyframes').length, 3);
});
